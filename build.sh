#!/bin/zsh
set -euo pipefail
project_root="${0:A:h}"
host_arch=$(/usr/bin/uname -m)
build_arch="$host_arch"
app_path="$project_root/build/Wakecup.app"
while (( $# )); do
  case "$1" in
    --arch|--output)
      (( $# >= 2 )) || { print -u2 "Missing value for $1"; exit 2; }
      if [[ "$1" == --arch ]]; then build_arch="$2"; else app_path="${2:a}"; fi
      shift 2 ;;
    *) print -u2 "Usage: $0 [--arch arm64|x86_64] [--output /path/Wakecup.app]"; exit 2 ;;
  esac
done
[[ "$build_arch" == arm64 || "$build_arch" == x86_64 ]] || { print -u2 'Unsupported architecture'; exit 2; }
[[ "${app_path:t}" == Wakecup.app && ! -L "$app_path" ]] || { print -u2 'Output must be a non-symlink Wakecup.app'; exit 2; }
[[ ! -e "$app_path" || -d "$app_path" ]] || { print -u2 'Output already exists and is not a directory'; exit 2; }
# Local builds stay ad-hoc signed. Releases require a pinned certificate SHA-1.
# Sign the helper BEFORE embedding its hashes; never re-sign a finished bundle.
signing_identity="${WAKECUP_SIGNING_IDENTITY:--}"
if [[ "$signing_identity" != - && ! "$signing_identity" =~ '^[A-Fa-f0-9]{40}$' ]]; then
  print -u2 'WAKECUP_SIGNING_IDENTITY must be a full certificate SHA-1 fingerprint'; exit 2
fi
if [[ "${WAKECUP_REQUIRE_RELEASE_SIGNING:-0}" == 1 && "$signing_identity" == - ]]; then
  print -u2 'Release signing is required; configure WAKECUP_SIGNING_IDENTITY'; exit 2
fi
sign_binary() {
  local target="$1" identifier="$2"
  local requirement="designated => certificate leaf = H\"$signing_identity\" and identifier \"$identifier\""
  if [[ "$signing_identity" == - ]]; then
    /usr/bin/codesign --force --options runtime --identifier "$identifier" --sign - "$target"
  else
    /usr/bin/codesign --force --options runtime --timestamp=none --identifier "$identifier" \
      -r="$requirement" --sign "$signing_identity" "$target"
    /usr/bin/codesign --verify --strict -R="certificate leaf = H\"$signing_identity\" and identifier \"$identifier\"" "$target"
  fi
}
deployment_target=$(/usr/bin/plutil -extract LSMinimumSystemVersion raw -o - "$project_root/Info.plist")
output_dir="${app_path:h}"
mkdir -p "$output_dir" "$project_root/.build/module-cache"
# A fresh sibling stage prevents removed resources from surviving rebuilds.
stage=$(/usr/bin/mktemp -d "$output_dir/.Wakecup-stage-XXXXXXXX")
staged_app="$stage/Wakecup.app"
backup=''
promoted=false
committed=false
sidecars_started=false
sidecars=()
cleanup() {
  local result=$?
  local rollback_failed=false
  if [[ "$committed" == false ]]; then
    if [[ "$sidecars_started" == true ]]; then
      for sidecar in "${sidecars[@]}"; do
        if [[ -f "$stage/previous-sidecars/${sidecar:t}" ]]; then
          /bin/cp -p "$stage/previous-sidecars/${sidecar:t}" "$sidecar" || { rollback_failed=true; print -u2 "Could not restore $sidecar"; }
        else
          /bin/rm -f "$sidecar" || { rollback_failed=true; print -u2 "Could not restore absent sidecar $sidecar"; }
        fi
      done
    fi
    # Move only this build's new bundle back into its owned stage, then restore.
    if [[ "$promoted" == true && ! -e "$staged_app" ]]; then
      /bin/mv "$app_path" "$staged_app" || { rollback_failed=true; print -u2 "Could not roll back $app_path"; }
    fi
    if [[ -n "$backup" && -d "$backup/Wakecup.app" && ! -e "$app_path" ]]; then
      /bin/mv "$backup/Wakecup.app" "$app_path" || { rollback_failed=true; print -u2 "Previous app remains at $backup/Wakecup.app"; }
    fi
    [[ -z "$backup" ]] || /bin/rmdir "$backup" 2>/dev/null || true
  fi
  if [[ "$rollback_failed" == true ]]; then
    print -u2 "Retained rollback files for recovery: $stage"
  else
    /bin/rm -rf "$stage"
  fi
  return "$result"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
mkdir -p "$staged_app/Contents/MacOS" "$staged_app/Contents/Resources/Helper"
cp "$project_root/Info.plist" "$staged_app/Contents/Info.plist"
cp -R "$project_root/Resources/." "$staged_app/Contents/Resources/"
cp "$project_root/LICENSE" "$staged_app/Contents/Resources/LICENSE.txt"
helper_path="$staged_app/Contents/Resources/Helper/local.wakecup.helper"
swiftc "$project_root"/Core/*.swift "$project_root"/System/*.swift "$project_root/Helper/main.swift" \
  -o "$helper_path" -target "$build_arch-apple-macos$deployment_target" \
  -module-cache-path "$project_root/.build/module-cache" -framework IOKit
sign_binary "$helper_path" local.wakecup.helper
helper_sha=$(/usr/bin/shasum -a 256 "$helper_path" | /usr/bin/awk '{print $1}')
helper_cdhash=$(/usr/bin/codesign -dvvv "$helper_path" 2>&1 | /usr/bin/awk -F= '$1 == "CDHash" {print $2}')
[[ ${#helper_sha} == 64 && ${#helper_cdhash} == 40 ]]
cat > "$stage/HelperBuildIdentity.swift" <<IDENTITY
// Generated by build.sh from the signed helper executable.
enum HelperBuildIdentity {
    static let sha256 = "$helper_sha"
    static let cdHash = "$helper_cdhash"
}
IDENTITY
sources=("$stage/HelperBuildIdentity.swift" "$project_root"/App/*.swift "$project_root"/Application/*.swift
         "$project_root"/Core/*.swift "$project_root"/System/*.swift "$project_root"/Presentation/*.swift)
swiftc "${sources[@]}" -o "$staged_app/Contents/MacOS/Wakecup" \
  -target "$build_arch-apple-macos$deployment_target" \
  -module-cache-path "$project_root/.build/module-cache" \
  -framework SwiftUI -framework AppKit -framework IOKit -framework ServiceManagement
icon_set="$stage/Wakecup.iconset"
mkdir -p "$icon_set"
for side in 16 32 128 256 512; do
  /usr/bin/sips -z "$side" "$side" "$project_root/Resources/Artwork/WakecupIcon.png" \
    --out "$icon_set/icon_$side"x"$side.png" >/dev/null
  retina=$((side * 2))
  /usr/bin/sips -z "$retina" "$retina" "$project_root/Resources/Artwork/WakecupIcon.png" \
    --out "$icon_set/icon_$side"x"$side@2x.png" >/dev/null
done
/usr/bin/iconutil -c icns "$icon_set" -o "$staged_app/Contents/Resources/Wakecup.icns"
# Generate identical guide text on the host, including when cross-compiling.
# Bundle.main must see the same translations as the shipped application.
guide_app="$stage/GuideGenerator.app"
mkdir -p "$guide_app/Contents/MacOS" "$guide_app/Contents/Resources"
cp "$project_root/Info.plist" "$guide_app/Contents/Info.plist"
cp -R "$project_root/Resources/." "$guide_app/Contents/Resources/"
cat > "$stage/main.swift" <<'GUIDE'
import Foundation
let language = AppLanguage(rawValue: CommandLine.arguments[1])!
print(SleepRecoveryGuide.plainText(language: language), terminator: "")
GUIDE
swiftc "$project_root/Core/AppLanguage.swift" "$project_root/Application/AppLocalization.swift" \
  "$project_root/Presentation/SleepRecoveryGuide.swift" "$stage/main.swift" \
  -o "$guide_app/Contents/MacOS/Wakecup" -target "$host_arch-apple-macos$deployment_target" \
  -module-cache-path "$project_root/.build/module-cache"
for language in en ru; do
  "$guide_app/Contents/MacOS/Wakecup" "$language" > "$staged_app/Contents/Resources/RecoveryGuide.$language.txt"
done
sign_binary "$staged_app" local.wakecup
"$project_root/Tests/BuildMetadataTests.sh" "$staged_app" "$build_arch"
if [[ "$build_arch" == "$host_arch" ]]; then
  "$staged_app/Contents/MacOS/Wakecup" --helper-self-test
else
  print -r -- "Cross-compiled $build_arch: runtime execution requires a matching Mac; static verification passed."
fi
# Snapshot only the default build's managed sidecars so promotion can roll them
# back with the app. Isolated/release builds never alter the default identity.
if [[ "$app_path" == "$project_root/build/Wakecup.app" ]]; then
  sidecars=("$project_root/.build/HelperBuildIdentity.swift" "$output_dir/RecoveryGuide.en.txt"
            "$output_dir/RecoveryGuide.ru.txt")
  mkdir -p "$stage/previous-sidecars"
  for sidecar in "${sidecars[@]}"; do
    [[ ! -L "$sidecar" && ( ! -e "$sidecar" || -f "$sidecar" ) ]] || {
      print -u2 "Refusing to overwrite a nonregular build sidecar: $sidecar"; exit 1
    }
    if [[ -f "$sidecar" ]]; then /bin/cp -p "$sidecar" "$stage/previous-sidecars/${sidecar:t}"; fi
  done
fi
# Promotion starts only after compilation, signing and all verification succeeded.
# Retain the previous local bundle; it may still be in use by a running process.
if [[ -e "$app_path" ]]; then
  backup=$(/usr/bin/mktemp -d "$output_dir/.Wakecup-backup-XXXXXXXX")
  /bin/mv "$app_path" "$backup/Wakecup.app"
fi
promoted=true
/bin/mv "$staged_app" "$app_path"
if (( ${#sidecars} )); then
  sidecars_started=true
  cp "$stage/HelperBuildIdentity.swift" "$project_root/.build/HelperBuildIdentity.swift"
  for language in en ru; do
    cp "$app_path/Contents/Resources/RecoveryGuide.$language.txt" "$output_dir/RecoveryGuide.$language.txt"
  done
fi
committed=true
[[ -z "$backup" ]] || print -r -- "Previous app retained: $backup/Wakecup.app"
print -r -- "$app_path"
